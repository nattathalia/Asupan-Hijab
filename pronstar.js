const menuBtn =
    document.getElementById(
        "menuBtn"
    );


const sidebar =
    document.getElementById(
        "sidebar"
    );


const overlay =
    document.getElementById(
        "overlay"
    );


/* ======================================================
   BUKA SIDEBAR
====================================================== */

function openSidebar(){

    if(!sidebar || !overlay){

        return;

    }


    sidebar.classList.add(
        "active"
    );


    overlay.classList.add(
        "active"
    );


    document.body.style.overflow =
        "hidden";

}


/* ======================================================
   TUTUP SIDEBAR
====================================================== */

function closeSidebar(){

    if(!sidebar || !overlay){

        return;

    }


    sidebar.classList.remove(
        "active"
    );


    overlay.classList.remove(
        "active"
    );


    document.body.style.overflow =
        "";

}


/* ======================================================
   INIT SIDEBAR
====================================================== */

function initSidebar(){

    if(
        !menuBtn ||
        !sidebar ||
        !overlay
    ){

        return;

    }


    /* ------------------------------------------
       TOMBOL MENU
    ------------------------------------------ */

    menuBtn.addEventListener(
        "click",
        function(){

            if(
                sidebar.classList.contains(
                    "active"
                )
            ){

                closeSidebar();

            }else{

                openSidebar();

            }

        }
    );


    /* ------------------------------------------
       OVERLAY
    ------------------------------------------ */

    overlay.addEventListener(
        "click",
        function(){

            closeSidebar();

        }
    );


    /* ------------------------------------------
       MENU SIDEBAR
    ------------------------------------------ */

    const menuItems =
        document.querySelectorAll(
            ".menu-item"
        );


    menuItems.forEach(
        function(item){

            item.addEventListener(
                "click",
                function(){

                    closeSidebar();

                }
            );

        }
    );

}


/* ======================================================
   MENU AKTIF SESUAI HALAMAN
====================================================== */

function initActiveMenu(){

    const currentPage =

        window.location.pathname

            .split("/")

            .pop()

            .toLowerCase();


    const menuLinks =
        document.querySelectorAll(
            ".menu-item"
        );


    menuLinks.forEach(
        function(link){

            const href =
                link.getAttribute(
                    "href"
                );


            if(!href){

                return;

            }


            const linkPage =

                href

                    .split("/")

                    .pop()

                    .toLowerCase();


            if(
                linkPage ===
                currentPage
            ){

                link.classList.add(
                    "active"
                );

            }else{

                link.classList.remove(
                    "active"
                );

            }

        }
    );

}


/* ======================================================
   HEADER SHADOW
====================================================== */

function initHeaderShadow(){

    const header =
        document.querySelector(
            "header"
        );


    if(!header){

        return;

    }


    window.addEventListener(
        "scroll",
        function(){

            if(
                window.scrollY > 50
            ){

                header.style.boxShadow =

                    "0 6px 18px rgba(0,0,0,.25)";

            }else{

                header.style.boxShadow =

                    "0 2px 8px rgba(0,0,0,.15)";

            }

        }
    );

}


/* ======================================================
   SCROLL TO TOP
====================================================== */

function initScrollTop(){

    let topButton =
        document.getElementById(
            "topButton"
        );


    /* ------------------------------------------
       BUAT TOMBOL JIKA BELUM ADA
    ------------------------------------------ */

    if(!topButton){

        topButton =
            document.createElement(
                "button"
            );


        topButton.id =
            "topButton";


        topButton.innerHTML =
            '<i class="fa-solid fa-arrow-up"></i>';


        topButton.setAttribute(
            "aria-label",
            "Kembali ke atas"
        );


        document.body.appendChild(
            topButton
        );

    }


    /* ------------------------------------------
       TAMPIL / SEMBUNYI
    ------------------------------------------ */

    window.addEventListener(
        "scroll",
        function(){

            if(
                window.scrollY > 300
            ){

                topButton.style.display =
                    "flex";


                topButton.style.alignItems =
                    "center";


                topButton.style.justifyContent =
                    "center";

            }else{

                topButton.style.display =
                    "none";

            }

        }
    );


    /* ------------------------------------------
       KLIK
    ------------------------------------------ */

    topButton.addEventListener(
        "click",
        function(){

            window.scrollTo({

                top: 0,

                behavior: "smooth"

            });

        }
    );

}


/* ======================================================
   ESC UNTUK SIDEBAR
====================================================== */

function initEscape(){

    document.addEventListener(
        "keydown",
        function(event){

            if(
                event.key ===
                "Escape"
            ){

                closeSidebar();

            }

        }
    );

}


